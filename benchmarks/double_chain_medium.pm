const int N = 2500;

module grid

	c : [0..N] init 0;
	f : [0..1] init 0;
	g : [0..1] init 0;

	[] c < N & f = 0 & g = 0 -> 
	           1/10: (c'=c)&(f'=f+1)&(g'=g) 
		+   1/10000: (c'=c)&(f'=f)&(g'=g+1) 
		+   8999/10000: (c'=c+1)&(f'=f)&(g'=g);
	
	[] c < N & f = 0 & g = 1 -> 
	           1/10: (c'=c)&(f'=f+1)&(g'=g) 
		+   1/10000: (c'=c)&(f'=f)&(g'=g) 
		+   8999/10000: (c'=c+1)&(f'=f)&(g'=g);

	[] c < N & f = 1 & g=0 -> 
		  1/1000: (c'=c)&(f'=f)&(g'=g+1) 
		+ 999/1000: (c'=c+1)&(f'=f)&(g'=g);

	[] c < N & f = 1 & g=1 -> 
		  1/1000: (c'=c)&(f'=f)&(g'=g) 
		+ 999/1000: (c'=c+1)&(f'=f)&(g'=g);

endmodule


label "goal" = g=1;
