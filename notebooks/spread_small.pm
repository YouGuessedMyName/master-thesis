module spread

	x : [0..4];
    y : [0..16] init 8;

    [] x = 0 & 0 < y & y < 16 ->   	1/2: (x'=x+1) & (y'=y-4) + 1/2: (x'=x+1) & (y'=y+4);
    [] x = 1 & 0 < y & y < 16 ->   	1/2: (x'=x+1) & (y'=y-2) + 1/2: (x'=x+1) & (y'=y+2);
    [] x = 2 & 0 < y & y < 16 ->   	1/2: (x'=x+1) & (y'=y-1) + 1/2: (x'=x+1) & (y'=y+1);
    [] x = 3 & 0 < y & y < 16 ->   	1/2: (x'=x+1) & (y'=y-1) + 1/2: (x'=x+1) & (y'=y);
endmodule

